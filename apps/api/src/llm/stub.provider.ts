import type { LLMProvider, LLMRequest, LLMResponse } from "./types.js";

/**
 * Deterministic offline provider. It keeps the full execution path (task ->
 * run -> events -> persistence) working without credentials, which is what
 * tests and local demos use by default.
 */
export class StubProvider implements LLMProvider {
  readonly id = "stub";
  readonly defaultModel = "stub-research-v1";

  async complete(request: LLMRequest): Promise<LLMResponse> {
    const prompt =
      request.messages.filter((message) => message.role === "user").at(-1)
        ?.content ?? "";

    return {
      text: [
        `Offline research summary for: ${prompt}`,
        "",
        `- Topic: ${prompt}`,
        "- Status: generated by the stub provider (no network call).",
        "- To use a real model, set LLM_PROVIDER and LLM_API_KEY.",
      ].join("\n"),
      provider: this.id,
      model: this.defaultModel,
    };
  }
}
